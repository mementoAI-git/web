import type { ConversationState, UseEveAgentHelpers } from "eve/react";

type StreamEvent = UseEveAgentHelpers<ConversationState>["events"][number];
const metricEventTypes = [
  "turn.started",
  "turn.completed",
  "turn.failed",
  "turn.cancelled",
  "step.started",
  "step.completed",
  "turn.waiting",
  "session.waiting",
  "session.failed",
  "session.completed",
] as const;
type MetricEvent = Extract<
  StreamEvent,
  { type: (typeof metricEventTypes)[number] }
>;
const metricTypes = new Set<string>(metricEventTypes);

/** Selects events that contain timing or provider usage.
 * @param event - A typed authoritative session event.
 * @returns Whether the event is relevant to tester metrics.
 */
function isMetricEvent(event: StreamEvent): event is MetricEvent {
  return metricTypes.has(event.type);
}

/** Provider-reported cumulative metrics; absent fields were not reported. */
interface ReportedUsage {
  /** Tokens used as model input. */
  readonly inputTokens?: number;
  /** Tokens generated by the model. */
  readonly outputTokens?: number;
  /** Model token cost reported by the provider, in USD. */
  readonly costUsd?: number;
}

/** Metrics derived from the authoritative session stream. */
interface ChatMetrics {
  /** Elapsed server time of the last settled turn, or unavailable. */
  readonly lastResponseMs: number | null;
  /** Latest reported model, falling back to the configured default. */
  readonly model: string;
  /** Cumulative usage reported so far, or unavailable. */
  readonly usage: ReportedUsage | null;
}

/** Derives tester metrics without estimating missing timestamps or provider usage.
 * @param events - Authoritative Eve events in durable stream order.
 * @returns Last settled turn duration and reported cumulative session usage.
 */
export function getChatMetrics(events: readonly StreamEvent[]): ChatMetrics {
  const starts = new Map<string, string>();
  const seen = new Set<string>();
  let lastResponseMs: number | null = null;
  let model = "deepseek-flash";
  let usage: ReportedUsage | null = null;
  for (const event of events.filter(isMetricEvent)) {
    if (seen.has(event.meta.id)) {
      continue;
    }
    seen.add(event.meta.id);
    switch (event.type) {
      case "turn.started": {
        starts.set(event.data.turnId, event.meta.at);
        break;
      }
      case "turn.completed":
      case "turn.failed":
      case "turn.cancelled": {
        lastResponseMs = elapsedTime(
          starts.get(event.data.turnId),
          event.meta.at
        );
        break;
      }
      case "step.started": {
        model = event.data.modelId;
        break;
      }
      case "step.completed": {
        usage = addReportedUsage(usage, event.data.usage);
        break;
      }
      case "turn.waiting":
      case "session.waiting":
      case "session.failed":
      case "session.completed": {
        const reportedUsage = event.data?.usage;
        if (reportedUsage !== undefined) {
          usage = addReportedUsage(null, reportedUsage);
        }
        break;
      }
      default: {
        break;
      }
    }
  }
  return { lastResponseMs, model, usage };
}

/** Measures a settled turn only when both server timestamps are usable.
 * @param started - Matching start timestamp, if present.
 * @param settled - Terminal event timestamp.
 * @returns Nonnegative elapsed milliseconds, or unavailable.
 */
function elapsedTime(
  started: string | undefined,
  settled: string
): number | null {
  if (started === undefined) {
    return null;
  }
  const elapsed = Date.parse(settled) - Date.parse(started);
  return Number.isFinite(elapsed) && elapsed >= 0 ? elapsed : null;
}

/** Adds only usage fields that the provider actually supplied.
 * @param previous - Previously reported totals.
 * @param next - New model usage, or a session snapshot when previous is null.
 * @returns The combined reported fields, or unavailable.
 */
function addReportedUsage(
  previous: ReportedUsage | null,
  next: ReportedUsage | undefined
): ReportedUsage | null {
  if (next === undefined) {
    return previous;
  }
  const combined = { ...previous };
  for (const key of ["inputTokens", "outputTokens", "costUsd"] as const) {
    const value = next[key];
    if (value !== undefined && Number.isFinite(value) && value >= 0) {
      combined[key] = (previous?.[key] ?? 0) + value;
    }
  }
  return Object.keys(combined).length === 0 ? null : combined;
}
