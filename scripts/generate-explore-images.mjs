import { createHash } from "node:crypto";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(SCRIPT_DIR, "..");
const MASTER_DIR = path.join(ROOT_DIR, "src/assets/image/categories/masters");
const OUTPUT_DIR = path.join(ROOT_DIR, "src/assets/image/categories/generated");
const MANIFEST_PATH = path.join(ROOT_DIR, "src/features/explore/explore-category-artwork.generated.ts");
const CACHE_PATH = path.join(OUTPUT_DIR, ".explore-image-cache.json");

const CATEGORIES = [
  "growing-up",
  "people-i-love",
  "the-life-i-live",
  "things-i-love",
  "who-i-am",
  "work-purpose",
  "beliefs-faith",
  "where-i-come-from",
  "stories-adventures",
  "what-life-taught-me",
  "whats-ahead",
];

const TARGET_WIDTHS = [480, 768, 1024, 1440];
const QUALITY = 82;
const PIPELINE_VERSION = 1;
const FORCE = process.argv.includes("--force");

const toIdentifier = (slug, width) =>
  `${slug.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()).replace(/-/g, "")}W${width}`;

const toImportPath = (filename) => `../../assets/image/categories/generated/${filename}`;

async function readCache() {
  try {
    return JSON.parse(await readFile(CACHE_PATH, "utf8"));
  } catch {
    return {};
  }
}

async function exists(filePath) {
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
}

async function sourceHash(filePath) {
  return createHash("sha256").update(await readFile(filePath)).digest("hex");
}

function renderManifest(entries) {
  const imports = entries.flatMap((entry) =>
    entry.variants.map(({ filename, width }) =>
      `import ${toIdentifier(entry.slug, width)} from "${toImportPath(filename)}";`,
    ),
  );

  const records = entries.map((entry) => {
    const variants = entry.variants
      .map(({ width, height }) => `      { src: ${toIdentifier(entry.slug, width)}, width: ${width}, height: ${height} },`)
      .join("\n");

    return `  "${entry.slug}": {
    src: ${toIdentifier(entry.slug, entry.variants[0].width)},
    width: ${entry.width},
    height: ${entry.height},
    variants: [
${variants}
    ],
  },`;
  });

  return `/* This file is generated by npm run images:explore. Do not edit manually. */
${imports.join("\n")}

export interface ExploreCategoryArtworkVariant {
  src: string;
  width: number;
  height: number;
}

export interface ExploreCategoryArtwork {
  src: string;
  srcSet: string;
  width: number;
  height: number;
  variants: ExploreCategoryArtworkVariant[];
}

const artwork = {
${records.join("\n")}
} as const;

export const exploreCategoryArtwork: Record<string, ExploreCategoryArtwork> = Object.fromEntries(
  Object.entries(artwork).map(([slug, item]) => [
    slug,
    {
      ...item,
      variants: [...item.variants],
      srcSet: item.variants.map((variant) => \`\${variant.src} \${variant.width}w\`).join(", "),
    },
  ]),
);
`;
}

await mkdir(OUTPUT_DIR, { recursive: true });
const previousCache = await readCache();
const nextCache = {};
const entries = [];

for (const slug of CATEGORIES) {
  const inputPath = path.join(MASTER_DIR, `${slug}.png`);
  if (!(await exists(inputPath))) {
    throw new Error(`Missing Explore master image: ${inputPath}`);
  }

  const metadata = await sharp(inputPath).metadata();
  if (!metadata.width || !metadata.height) {
    throw new Error(`Could not read dimensions for ${inputPath}`);
  }

  const widths = TARGET_WIDTHS.filter((width) => width <= metadata.width);
  if (widths.length === 0) widths.push(metadata.width);
  const hash = await sourceHash(inputPath);
  const cacheKey = JSON.stringify({ hash, widths, quality: QUALITY, version: PIPELINE_VERSION });
  const variants = widths.map((width) => ({
    width,
    height: Math.round((metadata.height * width) / metadata.width),
    filename: `${slug}-${width}.webp`,
  }));
  const outputsExist = (await Promise.all(variants.map(({ filename }) => exists(path.join(OUTPUT_DIR, filename))))).every(Boolean);

  if (FORCE || previousCache[slug] !== cacheKey || !outputsExist) {
    for (const variant of variants) {
      await sharp(inputPath)
        .resize({ width: variant.width, withoutEnlargement: true })
        .webp({ quality: QUALITY, smartSubsample: true, effort: 6 })
        .toFile(path.join(OUTPUT_DIR, variant.filename));
    }
    process.stdout.write(`Generated ${slug}: ${widths.join(", ")}px\n`);
  } else {
    process.stdout.write(`Unchanged ${slug}\n`);
  }

  nextCache[slug] = cacheKey;
  entries.push({ slug, width: metadata.width, height: metadata.height, variants });
}

await writeFile(CACHE_PATH, `${JSON.stringify(nextCache, null, 2)}\n`);
await writeFile(MANIFEST_PATH, renderManifest(entries));
process.stdout.write(`Wrote ${path.relative(ROOT_DIR, MANIFEST_PATH)} at WebP quality ${QUALITY}.\n`);
